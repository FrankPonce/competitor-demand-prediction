"""Shared skill taxonomy used for all four companies.

Structure: CATEGORY -> {"tech": bool, "skills": {canonical name: [aliases]}}

Alias syntax
    plain text     case-insensitive phrase; an optional plural "s"/"es" is allowed at the end
    "cs:..."       case-sensitive phrase (for words that are also ordinary English: Go, Rust, Spark, Excel)
    "re:..."       raw regular expression, case-insensitive
    "csre:..."     raw regular expression, case-sensitive

Seeded from the most frequent terms in the corpus' requirements / preferred / responsibilities
sections (2026-11-09), then extended with standard industry vocabulary. "tech": True categories
make up `tech_stack_tags`.
"""

LANG_CTX = r"(?:fluen\w*|proficien\w*|native|speak\w*|written|spoken|verbal|business[- ]level|bilingual|language)"


def spoken(lang: str) -> str:
    """Language skill only when it appears near a proficiency cue (avoids 'French market')."""
    return (rf"re:(?:{LANG_CTX}[^.\n]{{0,50}}\b{lang}\b|\b{lang}\b[^.\n]{{0,30}}{LANG_CTX})")


