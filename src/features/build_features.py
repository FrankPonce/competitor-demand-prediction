"""Sprint 4: skill extraction + feature engineering.

Usage (repo root):
    python -m src.features.build_features

Input    data/processed/corpus.parquet   (Sprint 3)
Outputs  data/features/posting_features.parquet / .csv   one row per posting, no raw text
         data/features/skills_long.csv                   one row per (posting, skill), with sections
         data/features/skill_matrix.parquet              posting x skill binary matrix
         reports/skills/company_skill_share.csv          % of postings mentioning each skill, by company
         reports/skills/company_category_share.csv       % of postings mentioning each category
         reports/skills/role_family_mix.csv / seniority_mix.csv
         reports/skills/summary.md                       generated tables
         reports/skills/spot_check.csv                   random matches with context for precision review
"""

from __future__ import annotations

import time
from pathlib import Path

import pandas as pd

from .extract import SKILLS, education, match_skills, min_years_experience, role_family, seniority, snippets
from .taxonomy import TAXONOMY

ROOT = Path(__file__).resolve().parents[2]
CORPUS = ROOT / "data" / "processed" / "corpus.parquet"
OUT = ROOT / "data" / "features"
REP = ROOT / "reports" / "skills"

SKILL_CAT = {s.name: s.category for s in SKILLS}
SKILL_TECH = {s.name: s.tech for s in SKILLS}

META = ["job_id", "company_name", "job_title", "posting_date", "first_seen_date", "last_seen_date", "job_status",
        "location", "job_url", "employment_type", "department", "job_category", "remote_type", "salary_min",
        "salary_max", "source_name", "in_live", "in_epoch", "language"]


def build(df: pd.DataFrame) -> tuple[pd.DataFrame, pd.DataFrame]:
    rows, long = [], []
    for r in df.itertuples(index=False):
        sections = {
            "requirements": r.section_requirements,
            "preferred": r.section_preferred,
            "responsibilities": r.section_responsibilities,
            "context": f"{r.section_intro}\n{r.section_about}",
        }
        found = match_skills(sections)
        family = role_family(r.job_title, r.department)
        if family == "Sales & Go-to-Market":
            # In sales postings "procurement" is the *customer's* buying process, not a skill.
            found.pop("Procurement & Vendor Management", None)
        years = min_years_experience(r.section_requirements, r.clean_text)
        level, is_mgr = seniority(r.job_title, years)
        edu = education(r.section_requirements, r.section_preferred, r.clean_text)
        skills = sorted(found)
        cats = sorted({SKILL_CAT[s] for s in skills})
        tech = [s for s in skills if SKILL_TECH[s]]
        rows.append({
            **{c: getattr(r, c) for c in META},
            "role_family": family,
            "seniority_level": level,
            "is_people_manager": is_mgr,
            "min_years_experience": years,
            **edu,
            "n_skills": len(skills),
            "n_tech_skills": len(tech),
            "n_required_skills": sum("requirements" in found[s] for s in skills),
            "extracted_skills": "; ".join(skills),
            "skill_categories": "; ".join(cats),
            "tech_stack_tags": "; ".join(tech),
        })
        for s in skills:
            secs = found[s]
            long.append({
                "job_id": r.job_id, "company_name": r.company_name, "skill": s, "category": SKILL_CAT[s],
                "tech": SKILL_TECH[s], "in_requirements": "requirements" in secs,
                "in_preferred": "preferred" in secs, "in_responsibilities": "responsibilities" in secs,
                "in_context": "context" in secs,
            })
    return pd.DataFrame(rows), pd.DataFrame(long)


def share_tables(feat: pd.DataFrame, long: pd.DataFrame):
    n = feat.groupby("company_name").size()
    skill = (long.groupby(["company_name", "skill"]).size().unstack(0).fillna(0) / n).round(4)
    skill.insert(0, "category", skill.index.map(SKILL_CAT))
    cat = (long.drop_duplicates(["job_id", "category"]).groupby(["company_name", "category"]).size()
           .unstack(0).fillna(0) / n).round(4)
    role = pd.crosstab(feat["role_family"], feat["company_name"], normalize="columns").round(4)
    sen = pd.crosstab(feat["seniority_level"], feat["company_name"], normalize="columns").round(4)
    return skill, cat, role, sen


def pct(df: pd.DataFrame) -> pd.DataFrame:
    return df.map(lambda v: f"{v:.0%}" if isinstance(v, float) else v)


def write_summary(feat, long, skill, cat, role, sen, secs: float) -> None:
    companies = ["Anthropic", "OpenAI", "NVIDIA", "Google"]
    lines = [
        "# Skills & Features Summary (generated)", "",
        f"Generated by `python -m src.features.build_features` in {secs:.0f}s · {len(feat):,} postings · "
        f"{sum(len(c['skills']) for c in TAXONOMY.values())} skills in {len(TAXONOMY)} categories · "
        f"see [Sprint 4](../../docs/sprints/sprint-04-skill-extraction.md)", "",
        "> Shares are **% of each company's postings** that mention a skill. Google is an AI/ML-focused sample "
        "and NVIDIA covers the newest ~100 postings, so compare *patterns*, not raw counts.", "",
        "## Coverage", "",
    ]
    g = feat.groupby("company_name")
    cov = pd.DataFrame({
        "postings": g.size().map("{:,}".format),
        "median skills / posting": g["n_skills"].median().map("{:.0f}".format),
        "median tech skills / posting": g["n_tech_skills"].median().map("{:.0f}".format),
        "postings with ≥1 skill": g["n_skills"].apply(lambda s: (s > 0).mean()).map("{:.0%}".format),
        "years of experience stated": g["min_years_experience"].apply(lambda s: s.notna().mean()).map("{:.0%}".format),
        "median min. years": g["min_years_experience"].median().map("{:.0f}".format),
        "PhD mentioned": g["mentions_phd"].mean().map("{:.0%}".format),
        "people managers": g["is_people_manager"].mean().map("{:.0%}".format),
    }).T[companies]
    lines += [cov.to_markdown(), "", "## Top skills per company", ""]
    soft = {"Leadership & Collaboration", "Spoken Languages"}
    for c in companies:
        s = skill[[c, "category"]].sort_values(c, ascending=False)
        tech_top = s[s.index.map(SKILL_TECH)].head(12)[c]
        biz_top = s[~s.index.map(SKILL_TECH) & ~s["category"].isin(soft)].head(8)[c]
        soft_top = s[s["category"].isin(soft)].head(4)[c]
        lines += [f"### {c}", "",
                  "- **Technical:** " + " · ".join(f"{k} {v:.0%}" for k, v in tech_top.items()),
                  "- **Business & domain:** " + " · ".join(f"{k} {v:.0%}" for k, v in biz_top.items()),
                  "- **Collaboration & languages:** " + " · ".join(f"{k} {v:.0%}" for k, v in soft_top.items()),
                  ""]
    lines += ["## Skill categories", "", pct(cat[companies].sort_values("Anthropic", ascending=False)).to_markdown(), "",
              "## Role family mix", "", pct(role.reindex(columns=companies)).to_markdown(), "",
              "## Seniority mix", "", pct(sen.reindex(columns=companies)).to_markdown(), ""]
    tech = long[long.tech].groupby("skill").job_id.nunique().sort_values(ascending=False).head(25)
    lines += ["## Most common tech-stack tags (all companies)", "",
              " · ".join(f"{k} ({v})" for k, v in tech.items()), ""]
    REP.mkdir(parents=True, exist_ok=True)
    (REP / "summary.md").write_text("\n".join(lines), encoding="utf-8")


def spot_check(df: pd.DataFrame, long: pd.DataFrame, n: int = 100, seed: int = 7) -> pd.DataFrame:
    text = df.set_index("job_id")["clean_text"]
    sample = long.sample(n=min(n, len(long)), random_state=seed)
    rows = []
    for r in sample.itertuples(index=False):
        snip = snippets(text[r.job_id], r.skill)
        rows.append({"job_id": r.job_id, "company_name": r.company_name, "skill": r.skill,
                     "context": snip[0] if snip else "", "correct": ""})
    return pd.DataFrame(rows)


def main() -> None:
    t0 = time.time()
    df = pd.read_parquet(CORPUS)
    feat, long = build(df)
    OUT.mkdir(parents=True, exist_ok=True)
    feat.to_parquet(OUT / "posting_features.parquet", index=False)
    feat.to_csv(OUT / "posting_features.csv", index=False)
    long.to_csv(OUT / "skills_long.csv", index=False)
    matrix = pd.crosstab(long["job_id"], long["skill"]).clip(upper=1).astype("int8")
    matrix = matrix.reindex(feat["job_id"], fill_value=0)
    matrix.to_parquet(OUT / "skill_matrix.parquet")

    skill, cat, role, sen = share_tables(feat, long)
    REP.mkdir(parents=True, exist_ok=True)
    skill.to_csv(REP / "company_skill_share.csv")
    cat.to_csv(REP / "company_category_share.csv")
    role.to_csv(REP / "role_family_mix.csv")
    sen.to_csv(REP / "seniority_mix.csv")
    sc = REP / "spot_check.csv"
    if not sc.exists():  # don't overwrite a reviewed file
        spot_check(df, long).to_csv(sc, index=False)
    write_summary(feat, long, skill, cat, role, sen, time.time() - t0)
    print(f"{len(feat):,} postings, {len(long):,} skill mentions, {long.skill.nunique()} distinct skills "
          f"({time.time() - t0:.0f}s)")


if __name__ == "__main__":
    main()
